let three = "3"
let four = "4"
let thirty = "30"
//what is the value of the following expressions?
let addition = three + four // "34" addition of two strings results in a string

let multiplication = three * four // 12 both strings are converted to numbers because of multiplication operator

let division = three / four // 0.75 string "4" is converted to number 4 because of division operator

let subtraction = three - four // -1 string "4" is converted to number 4 because of subtraction operator

let lessThan1 = three < four // true string "3" is converted to number 3 and string "4" is converted to number 4 because of less than operator

let lessThan2 = thirty < four // false string "30" is converted to number 30 and string "4" is converted to number 4 because of less than operator